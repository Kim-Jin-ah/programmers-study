SELECT COUNT(*) AS FISH_COUNT, I.FISH_NAME
FROM FISH_INFO F
JOIN FISH_NAME_INFO I
    ON F.FISH_TYPE = I.FISH_TYPE
GROUP BY F.FISH_TYPE
ORDER BY FISH_COUNT DESC;
-- 1. JOIN ON 사용하기
  
SELECT COUNT(*) AS FISH_COUNT, FISH_NAME
FROM FISH_INFO
JOIN FISH_NAME_INFO
USING (FISH_TYPE)
GROUP BY FISH_TYPE
ORDER BY FISH_COUNT DESC;
-- 2. JOIN ~ USING 사용하기
  
SELECT TC.FISH_COUNT, I.FISH_NAME 
FROM (
    SELECT FISH_TYPE, COUNT(*) AS FISH_COUNT
    FROM FISH_INFO
    GROUP BY FISH_TYPE
) AS TC
INNER JOIN FISH_NAME_INFO I
ON TC.FISH_TYPE = I.FISH_TYPE
ORDER BY TC.FISH_COUNT DESC;
