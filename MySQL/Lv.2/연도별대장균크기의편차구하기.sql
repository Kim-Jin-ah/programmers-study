SELECT F.YEAR, (F.MAX_SIZE - E.SIZE_OF_COLONY) AS YEAR_DEV, E.ID
FROM ECOLI_DATA E
INNER JOIN (SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR, MAX(SIZE_OF_COLONY) AS MAX_SIZE
        FROM ECOLI_DATA
        GROUP BY YEAR) AS F
ON YEAR(E.DIFFERENTIATION_DATE) = F.YEAR
ORDER BY YEAR, YEAR_DEV;

