SELECT U.USER_ID, U.NICKNAME, CONCAT(CITY," ",STREET_ADDRESS1," ",STREET_ADDRESS2) AS 전체주소, CONCAT(SUBSTR(TLNO,1,3),"-",SUBSTR(TLNO,4,4),"-",SUBSTR(TLNO,8,4)) AS 전화번호
FROM USED_GOODS_USER U
INNER JOIN (SELECT WRITER_ID, COUNT(*) AS TOTAL
            FROM USED_GOODS_BOARD
            GROUP BY WRITER_ID) AS C
ON U.USER_ID = C.WRITER_ID
WHERE C.TOTAL >= 3
ORDER BY U.USER_ID DESC;

-- 풀이전략, 핵심 아이디어
-- 조인할 때
SELECT WRITER_ID
FROM USED_GOODS_BOARD
GROUP BY WRITER_ID
HAVING COUNT(*) >= 3;
