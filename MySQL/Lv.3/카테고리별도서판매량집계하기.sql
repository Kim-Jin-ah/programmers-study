SELECT
    B.CATEGORY,
    SUM(S.SALES) AS TOTAL_SALES
FROM BOOK B
JOIN BOOK_SALES S
    ON B.BOOK_ID = S.BOOK_ID
WHERE S.SALES_DATE >= '2022-01-01'
  AND S.SALES_DATE < '2022-02-01'
GROUP BY B.CATEGORY
ORDER BY B.CATEGORY ASC;
-- JOIN 후 GROUP BY

SELECT B.CATEGORY, SUM(S.TOTAL) AS TOTAL_SALES
FROM BOOK B
INNER JOIN (SELECT BOOK_ID, SUM(SALES) AS TOTAL
            FROM BOOK_SALES
            WHERE SALES_DATE LIKE '2022-01%'
            GROUP BY BOOK_ID) AS S
ON B.BOOK_ID = S.BOOK_ID
GROUP BY B.CATEGORY
ORDER BY B.CATEGORY;
