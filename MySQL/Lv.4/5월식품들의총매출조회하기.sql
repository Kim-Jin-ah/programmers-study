SELECT P.PRODUCT_ID, P.PRODUCT_NAME, (PRICE*TOTAL) AS TOTAL_SALES
FROM FOOD_PRODUCT P
JOIN (SELECT PRODUCT_ID, SUM(AMOUNT) AS TOTAL
        FROM FOOD_ORDER
        WHERE PRODUCE_DATE LIKE '2022-05%'
        GROUP BY PRODUCT_ID) I
ON P.PRODUCT_ID = I.PRODUCT_ID
ORDER BY TOTAL_SALES DESC, PRODUCT_ID;

-- 풀이전략, 핵심 아이디어
-- GROUP BY를 서브쿼리 안에서 처리해 메인쿼리에서는 추가적인 그룹화 없이 매출 계산과 정렬만
-- 날짜 컬럼 조회할 때 범위 조건을 사용하는 습관 들이기
WHERE PRODUCE_DATE >= '2022-05-01'
  AND PRODUCE_DATE < '2022-06-01'
